// 1. 黑名单: 拥有最高否决权。包含这些词的条目, 100%会被过滤。
const blacklist = [
  '套餐', '到期', '流量', '剩余', '重置', '官网', '过滤',
  '订阅', '频道', '群组', '公告', '禁止', '说明', '推荐', '机场',
  '客服', '链接', '过期', '已用', '点击', '网址', '教程',
  '追云国内', '追云国外', '未到期', '长期有效',
  '有效期', '到期时间', '流量统计', '使用情况', '账户', '余额',
  'Error', '错误', '失败', '维护', '更新中', '通知', '提示'
];

// 2. 白名单: 用于优先保留特征明显的节点。
const whitelist = [
  // 地区 - 中文
  '香港', '澳门', '台湾', '新加坡', '日本', '韩国', '美国', '英国', '德国', '法国', '俄罗斯', '印度', '土耳其', '越南', '马来西亚', '加拿大', '澳洲', '巴西', '阿根廷',
  '荷兰', '瑞士', '意大利', '西班牙', '泰国', '菲律宾', '印尼', '墨西哥', '智利', '南非', '埃及', '以色列', '迪拜', '波兰', '瑞典', '挪威', '丹麦', '芬兰', '爱尔兰', '葡萄牙', '希腊',
  // 城市 - 中文
  '东京', '首尔', '莫斯科', '伦敦', '纽约', '洛杉矶', '巴黎', '柏林', '阿姆斯特丹', '悉尼', '多伦多', '温哥华', '曼谷', '吉隆坡', '雅加达', '孟买',
  // 地区 - 英文缩写
  'HK', 'MO', 'TW', 'SG', 'JP', 'KR', 'US', 'UK', 'DE', 'FR', 'RU', 'IN', 'TR', 'VN', 'MY', 'CA', 'AU', 'NL', 'CH', 'IT', 'ES', 'TH', 'PH', 'ID', 'MX', 'CL', 'ZA', 'EG', 'IL', 'AE',
  // 线路特征
  '专线', 'IPLC', 'IEPL', 'BGP', 'CN2', 'GIA', '游戏', 'Game', '流媒体', 'Streaming', '解锁', '中转', 'Relay', 'Premium', 'Pro', 'VIP', '高速', '优化', '直连', '快速', '稳定'
];

// --- 核心逻辑区 ---

// 从全局变量 $server 中获取当前节点的名字
const name = $server.name;
const upperName = name.toUpperCase(); // 创建一个大写版本, 用于不区分大小写的匹配

// 第一步: 白名单检查 (最高优先级 - 保护合法节点)
for (let i = 0; i < whitelist.length; i++) {
  // 对白名单进行不区分大小写的检查
  if (upperName.indexOf(whitelist[i].toUpperCase()) !== -1) {
    return true; // 命中白名单, 立即保留
  }
}

// 第二步: 模式匹配检查 (过滤明显的信息条目)
// 匹配 "key: value" 格式的信息条目 (如: "剩余流量: 867.6 GB", "未到期: 长期有效")
if (/[:：]/.test(name)) {
  // 包含冒号的条目，检查是否为信息条目
  if (/[\u4e00-\u9fa5]+[:：]\s*[\d\.\s]+(GB|MB|TB|KB|天|小时|年|月|日)/i.test(name)) {
    return false; // 流量/时间统计信息
  }
  // 只过滤长度较短的纯中文键值对 (避免误杀 "东京: 高速" 这类节点名)
  if (/^[\u4e00-\u9fa5]{2,6}[:：]\s*[\u4e00-\u9fa5]{2,6}$/.test(name) && name.length < 12) {
    return false; // 短的纯中文键值对信息 (如: "未到期: 长期有效")
  }
}

// 过滤纯数字+单位的条目 (如: "867.6 GB")
if (/^[\d\.\s]+(GB|MB|TB|KB)$/i.test(name)) {
  return false;
}

// 第三步: 黑名单检查
for (let i = 0; i < blacklist.length; i++) {
  if (name.indexOf(blacklist[i]) !== -1) {
    return false; // 命中黑名单, 立即丢弃
  }
}

// 第三步: 启发式分析 (对不黑不白的“中性”条目进行最终裁定)
let features = 0;
// 特征1: 包含数字 (节点通常带编号)
if (/\d/.test(name)) {
  features++;
}
// 特征2: 包含英文字母 (很多节点名包含英文)
if (/[a-zA-Z]/.test(name)) {
  features++;
}
// 特征3: 名字长度合理 (太长或太短都可能是无效信息)
if (name.length > 2 && name.length < 40) {
  features++;
}

// 最终决策: 对于中性条目, 至少需要满足2个或以上特征才被认为是有效节点
return features >= 2;
